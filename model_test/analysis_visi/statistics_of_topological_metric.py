def draw_metric_scatter(fig,network,attributions,subplot_numCols=1):
    subplot_nums = len(attributions)
    subplot_numRows = int(np.ceil(subplot_nums / subplot_numCols))

    subplot_iter = 1
    for attribution in attributions:
        if attribution == "degree":
            degree=nx.degree_histogram(network)
            x=range(len(degree))
            pmf=[z/float(sum(degree)) for z in degree] # probability mass function
            cdf=[sum(pmf[index:]) for index in x] #cumulative distribution function
        ax = fig.add_subplot(subplot_numRows, subplot_numCols, subplot_iter)
        ax.loglog(x,pmf,".",color="g")

        ax.loglog(x,cdf,".",color="r")#双对数分布
        ax.set_ylabel("CDF")
        ax.set_xlabel(attribution )
        subplot_iter += 1
